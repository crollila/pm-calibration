"""Render LIVE_TRADING_CASE_STUDY.md from computed positions and summary.

No number in the document is typed by hand: every figure is formatted from the
`summary` dict or the position rows produced by `live.report.compute`.
"""

from __future__ import annotations

import math
from decimal import ROUND_HALF_UP, Decimal

from live.analytics import SIZE_ORDER
from live.ledger import OPEN, SETTLED

CENT = Decimal("0.01")


# ------------------------------------------------------------------ format
def usd(x, sign: bool = False) -> str:
    if x is None:
        return "n/a"
    d = Decimal(str(x)).quantize(CENT, rounding=ROUND_HALF_UP)
    body = f"${abs(d):,.2f}"
    if d < 0:
        return f"−{body}"
    return f"+{body}" if sign and d > 0 else body


def pct(x, digits: int = 1, sign: bool = True) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "n/a"
    v = float(x) * 100
    s = f"{v:+.{digits}f}%" if sign else f"{v:.{digits}f}%"
    return s.replace("-", "−")


def pts(x, digits: int = 1) -> str:
    """Probability difference in percentage points (no negative zero).

    >>> pts(-0.0000282, 2), pts(0.0123)
    ('0.00 pp', '+1.2 pp')
    """
    if x is None:
        return "n/a"
    v = round(float(x) * 100, digits)
    if v == 0:
        return f"{0:.{digits}f} pp"
    return f"{v:+.{digits}f} pp".replace("-", "−")


def ci(d: dict, fmt=pct) -> str:
    if not d or d.get("lo") is None or math.isnan(d["lo"]):
        return "n/a"
    return f"[{fmt(d['lo'])}, {fmt(d['hi'])}]"


def day(ts: str | None) -> str:
    return ts[:10] if ts else ""


def minute(ts: str | None) -> str:
    return f"{ts[:16].replace('T', ' ')}" if ts else ""


def num(x, digits: int = 2) -> str:
    if x is None or x == "":
        return ""
    d = Decimal(str(x))
    return f"{d:.{digits}f}"


def table(head: list[str], rows: list[list], align: str | None = None) -> str:
    align = align or "l" + "r" * (len(head) - 1)
    sep = ["---:" if a == "r" else "---" for a in align]
    lines = ["| " + " | ".join(head) + " |", "| " + " | ".join(sep) + " |"]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def group_rows(groups: list[dict], order: list[str] | None = None) -> list[list]:
    if order:
        groups = sorted(
            groups, key=lambda g: order.index(g["group"]) if g["group"] in order else 99
        )
    out = []
    for g in groups:
        held = g["held"]
        out.append(
            [
                g["group"],
                g["n"],
                f"{g['wins'] / g['n']:.0%}",
                usd(g["capital"]),
                usd(g["pnl"], sign=True),
                pct(g["roi"]),
                usd(g["fees"]),
                f"{g['held_won']:.0f} / {g['held_implied']:.1f}" if held else "—",
            ]
        )
    return out


