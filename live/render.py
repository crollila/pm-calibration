def _earlier_comparison(leagues: list[dict]) -> str:
    """Compare this ledger with the earlier note's segment claims (quoted, not recomputed)."""
    by = {x["group"]: x for x in leagues}
    parts = []
    if "cbb" in by:
        parts.append(
            f"college basketball, which the note found to be −2.6% over 126 positions, is "
            f"{pct(by['cbb']['roi'])} over {by['cbb']['n']} here"
        )
    if "nfl" in by:
        parts.append(
            f"NFL, +100.4% over 11 positions there, is {pct(by['nfl']['roi'])} over "
            f"{by['nfl']['n']} here, still too few to mean much"
        )
    return ("On the segments the note highlighted: " + "; ".join(parts) + ".") if parts else ""


def _market(r: dict) -> str:
    if r["kind"] == "combo":
        return f"Combo ({r['league']}): {r['market'][:70]}{'…' if len(r['market']) > 70 else ''}"
    return f"{r['market']} → {r['outcome']}"


def _exit(r: dict) -> str:
    parts = []
    if r["exit_price"] is not None:
        parts.append(f"sold {num(r['exit_price'], 3)}")
    if r["status"] == SETTLED:
        parts.append(f"settled {num(r['settle_price'], 2)}")
    return "; ".join(parts) or "—"


def _brief(r: dict) -> list:
    return [
        f"`{r['position_id']}`",
        minute(r["entry_utc"]),
        _market(r),
        r["side"],
        num(r["entry_price"], 3),
        usd(r["capital_at_risk"]),
        usd(r["realized_pnl"], True),
    ]
